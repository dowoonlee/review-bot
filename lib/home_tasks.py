"""Local home-task lifecycle. Dedicated lock; never posts or changes GitHub state."""
from contextlib import contextmanager
from concurrent.futures import ThreadPoolExecutor
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile
import time
import uuid

from lib import github, store


class TaskError(Exception):
    pass


def path():
    return Path(store.STATE_DIR) / 'home-tasks.json'


def load():
    try:
        data = json.loads(path().read_text())
        if not isinstance(data.get('tasks'), dict) or not isinstance(data.get('current'), dict): raise ValueError()
        return data
    except FileNotFoundError:
        return {'tasks': {}, 'current': {}}
    except (ValueError, OSError):
        raise TaskError('할 일 기록을 읽지 못했습니다') from None


@contextmanager
def edit():
    path().parent.mkdir(parents=True, exist_ok=True)
    with open(path().with_suffix('.lock'), 'a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        data = load()
        yield data
        fd, temp = tempfile.mkstemp(prefix='.home-tasks-', dir=path().parent)
        try:
            with os.fdopen(fd, 'w', encoding='utf-8') as file:
                json.dump(data, file, ensure_ascii=False)
            os.replace(temp, path())
        finally:
            if os.path.exists(temp): os.unlink(temp)


def now():
    return time.strftime('%Y-%m-%dT%H:%M:%S%z')


def identity(repo, number, account, direction):
    return '%s:%s:%s#%s' % (direction, account or 'global', repo, number)


def start(repo, number, account, direction, title='', label='', agent='manual', session_id=None, terminal_id=None):
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repo) or number <= 0 or direction not in ('incoming', 'outgoing'):
        raise TaskError('올바른 PR과 요청 방향이 필요합니다')
    def validate_id(value):
        if value is None: return None
        if agent not in ('codex', 'claude'):
            raise TaskError('Codex 또는 Claude를 선택해 주세요')
        try:
            return str(uuid.UUID(value.strip()))
        except (ValueError, AttributeError):
            raise TaskError('올바른 세션 ID(UUID)를 입력해 주세요') from None
    session_id, terminal_id = validate_id(session_id), validate_id(terminal_id)
    account = None if account in (None, '', 'global') else account
    key = identity(repo, number, account, direction)
    row = {'id': str(uuid.uuid4()), 'requestID': key, 'repo': repo, 'number': number,
           'account': account, 'direction': direction, 'title': title[:500], 'label': label[:300],
           'agent': agent, 'status': 'running', 'startedAt': now(), 'version': 0}
    if session_id is not None:
        row['sessionID'] = session_id
    if terminal_id is not None:
        row['terminalID'] = terminal_id
    with edit() as data:
        previous = data['tasks'].get(data['current'].get(key))
        if ((session_id is not None or terminal_id is not None) and previous and previous['status'] == 'running'
                and previous.get('sessionID') == session_id and previous.get('terminalID') == terminal_id
                and previous['agent'] == agent):
            return dict(previous)
        if previous: previous['status'] = 'superseded'
        data['tasks'][row['id']] = row
        data['current'][key] = row['id']
    return row


def current_task(data, task_id):
    row = data['tasks'].get(task_id)
    if not row or data['current'].get(row['requestID']) != task_id:
        raise TaskError('작업이 없거나 더 새 작업으로 대체되었습니다')
    return row


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def approved(meta):
    """필요한 승인이 모두 끝났는지. 보호 규칙이 없는 저장소는 리뷰어 전원 승인·대기 없음으로 본다."""
    decision = meta.get('reviewDecision')
    if decision: return decision == 'APPROVED'
    reviews = [r.get('state') for r in meta.get('latestReviews') or [] if isinstance(r, dict)]
    return bool(reviews) and all(state == 'APPROVED' for state in reviews) and not (meta.get('reviewRequests') or [])


def snapshot(row):
    repo, number, account = row['repo'], row['number'], row.get('account')
    viewer = account or github.whoami(account)
    with ThreadPoolExecutor(max_workers=3) as pool:
        conversation = pool.submit(github.request_context, repo, number, account=account, bounded=False)
        metadata = pool.submit(github.pr_meta, repo, number, account=account, timeout=30)
        request = pool.submit(github.last_review_request, repo, number, viewer, account=account, timeout=30) if row['direction'] == 'incoming' else None
        context, meta = conversation.result(), metadata.result()
        requested_at = ((request.result() if request else None) or {}).get('at')
    if not meta.get('headRefOid') or meta['headRefOid'] != context.get('head'):
        raise github.GhError('PR 커밋이 갱신 중입니다')
    # Ignore own completion notes and resolved discussions; don't treat wording regenerated by AI as new work.
    feedback = {}
    for source in context['sources']:
        if source['id'] == 'pr' or source.get('resolved') or (source.get('author') or '').lower() == (viewer or '').lower(): continue
        if source.get('state') in ('APPROVED', 'DISMISSED'): continue
        feedback[source['id']] = digest({k: source.get(k) for k in ('body', 'state', 'at', 'thread')})
    failures = {}
    for check in meta.get('statusCheckRollup') or []:
        if str(check.get('conclusion') or check.get('state') or '').upper() in ('FAILURE', 'ERROR', 'TIMED_OUT', 'ACTION_REQUIRED', 'STARTUP_FAILURE', 'CANCELLED'):
            check_id = digest([check.get('name') or check.get('context'), check.get('workflowName'), check.get('detailsUrl') or check.get('targetUrl')])
            failures[check_id] = digest([meta.get('headRefOid'), check])
    return {'state': meta.get('state'), 'head': meta.get('headRefOid'), 'updatedAt': meta.get('updatedAt'), 'requestedAt': requested_at,
            'feedback': feedback, 'failures': failures, 'conflict': meta.get('mergeable') == 'CONFLICTING',
            'approved': approved(meta) and not meta.get('isDraft'), 'incomplete': context.get('incomplete', False)}


def complete(task_id):
    row = dict(current_task(load(), task_id))
    if row['status'] == 'completed': return row
    if row['status'] not in ('running', 'reopened', 'stopped'):
        raise TaskError('완료할 수 없는 작업 상태입니다')
    try:
        baseline = snapshot(row)
    except (github.GhError, OSError, ValueError):
        raise TaskError('GitHub의 완료 기준을 확인하지 못했습니다. 완료 처리하지 않았으니 잠시 후 다시 시도해 주세요') from None
    with edit() as data:
        latest = current_task(data, task_id)
        if latest['status'] == 'completed': return dict(latest)
        if latest.get('version', 0) != row.get('version', 0):
            raise TaskError('작업 상태가 변경되어 완료 처리하지 않았습니다')
        if latest['status'] not in ('running', 'reopened', 'stopped'):
            raise TaskError('작업 상태가 변경되어 완료 처리하지 않았습니다')
        latest.update(status='completed', completedAt=now(), baseline=baseline, lastSyncError=None, version=latest.get('version', 0) + 1)
        return dict(latest)


def change(task_id, status):
    if status not in ('reopened', 'cancelled', 'stopped'): raise TaskError('지원하지 않는 상태입니다')
    with edit() as data:
        row = current_task(data, task_id)
        if status == 'stopped' and row['status'] != 'running': return dict(row)
        if row['status'] == 'completed' and status == 'cancelled': return dict(row)
        row.update(status=status, lastSyncError=None, version=row.get('version', 0) + 1)
        if status == 'reopened': row['reopenReason'] = '직접 다시 열었습니다'
        return dict(row)


def reason_for_reopen(row, current):
    old = row.get('baseline')
    if not old or current.get('state') in ('CLOSED', 'MERGED'): return None
    if current.get('updatedAt') and old.get('updatedAt') and current['updatedAt'] < old['updatedAt']: return None
    if current.get('requestedAt') and current['requestedAt'] > (old.get('requestedAt') or ''):
        return '새 리뷰 요청이 도착했습니다'
    if any(old.get('feedback', {}).get(k) != v for k, v in current.get('feedback', {}).items()):
        return '새 리뷰 의견 또는 질문이 있습니다'
    if any(old.get('failures', {}).get(k) != v for k, v in current.get('failures', {}).items()):
        return '새 CI 실패가 확인됐습니다'
    if current.get('conflict') and not old.get('conflict'): return '새 브랜치 충돌이 생겼습니다'
    if row['direction'] == 'outgoing' and current.get('approved') and not old.get('approved'):
        return '승인이 끝나 머지 조건을 확인할 차례입니다'
    if (current.get('incomplete') or old.get('incomplete')) and current.get('updatedAt') != old.get('updatedAt'):
        return '대화 일부만 확인되어 새 변경을 다시 확인해야 합니다'
    if row['direction'] == 'incoming' and old.get('head') != current.get('head'):
        return '완료 이후 새 커밋이 올라왔습니다'
    return None


def reconcile(visible):
    data = load()
    rows = [dict(data['tasks'][task_id]) for key, task_id in data['current'].items()
            if key in visible and data['tasks'][task_id].get('status') == 'completed']
    if not rows: return
    def check(row):
        try: return row, snapshot(row), None
        except (github.GhError, OSError, ValueError): return row, None, '새 요청 확인에 실패했습니다'
    with ThreadPoolExecutor(max_workers=3) as pool:
        results = list(pool.map(check, rows))
    with edit() as latest:
        for original, observed, error in results:
            row = latest['tasks'].get(original['id'])
            if not row or latest['current'].get(row['requestID']) != row['id'] or row['status'] != 'completed' or row.get('version') != original.get('version'): continue
            row['lastSyncError'] = error
            if error: continue
            reason = reason_for_reopen(row, observed)
            if reason:
                row.update(status='reopened', reopenedAt=now(), reopenReason=reason, version=row.get('version', 0) + 1)


def forget(repo, number):
    if not path().exists(): return
    with edit() as data:
        removed = {k for k, r in data['tasks'].items() if r.get('repo') == repo and r.get('number') == number}
        data['tasks'] = {k: r for k, r in data['tasks'].items() if k not in removed}
        data['current'] = {k: v for k, v in data['current'].items() if v not in removed}
